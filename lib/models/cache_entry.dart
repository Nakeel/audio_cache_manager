// lib/models/cache_entry.dart
import 'dart:io';
import 'package:hive/hive.dart';

import 'hls_segment_entry.dart' show HlsSegmentEntry;

part 'cache_entry.g.dart'; // This file will be generated by build_runner

@HiveType(typeId: 178)
class CacheEntry extends HiveObject {
  @HiveField(0)
  final String trackId;

  @HiveField(1)
  final String originalUrl;

  @HiveField(2)
  final String filePath; // For MP3s

  @HiveField(3)
  final DateTime timestamp;

  @HiveField(4)
  final int fileSize; // Total size of the cached content in bytes (sum of segments for HLS)

  @HiveField(5)
  final bool isEncrypted;

  @HiveField(6)
  final String etag;

  @HiveField(7)
  final String lastModified;

  @HiveField(8)
  final String contentType;

  @HiveField(9)
  final String proxyUrl; // This will be the internal http proxy path for the main entry

  // --- New fields for HLS caching ---
  @HiveField(10)
  final bool isHls;

  @HiveField(11)
  final String? hlsLocalPath; // Base directory for HLS segments and manifests
  @HiveField(12)
  final List<HlsSegmentEntry>? hlsSegments; // List of individual HLS segment statuses

  @HiveField(13) // NEW FIELD FOR DATA INTEGRITY
  final String? dataHash; // SHA-256 hash of the (decrypted) content for MP3s

  CacheEntry({
    required this.trackId,
    required this.originalUrl,
    required this.filePath,
    required this.timestamp,
    required this.fileSize,
    required this.isEncrypted,
    required this.etag,
    required this.lastModified,
    required this.contentType,
    required this.proxyUrl,
    this.isHls = false,
    this.hlsLocalPath,
    this.hlsSegments,
    this.dataHash, // NEW
  });

  CacheEntry copyWith({
    String? trackId,
    String? originalUrl,
    String? filePath,
    DateTime? timestamp,
    int? fileSize,
    bool? isEncrypted,
    String? etag,
    String? lastModified,
    String? contentType,
    String? proxyUrl,
    bool? isHls,
    String? hlsLocalPath,
    List<HlsSegmentEntry>? hlsSegments,
    String? dataHash, // NEW
  }) {
    return CacheEntry(
      trackId: trackId ?? this.trackId,
      originalUrl: originalUrl ?? this.originalUrl,
      filePath: filePath ?? this.filePath,
      timestamp: timestamp ?? this.timestamp,
      fileSize: fileSize ?? this.fileSize,
      isEncrypted: isEncrypted ?? this.isEncrypted,
      etag: etag ?? this.etag,
      lastModified: lastModified ?? this.lastModified,
      contentType: contentType ?? this.contentType,
      proxyUrl: proxyUrl ?? this.proxyUrl,
      isHls: isHls ?? this.isHls,
      hlsLocalPath: hlsLocalPath ?? this.hlsLocalPath,
      hlsSegments: hlsSegments ?? this.hlsSegments,
      dataHash: dataHash ?? this.dataHash, // NEW
    );
  }

  FileSystemEntity get cacheFileEntity {
    if (isHls) {
      return Directory(hlsLocalPath!);
    } else {
      return File(filePath);
    }
  }
}

